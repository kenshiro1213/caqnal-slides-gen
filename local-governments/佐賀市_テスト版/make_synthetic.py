"""佐賀市 テスト版の架空回答データ生成。seed 固定。実データは一切使わない。

作り込み: 部局差（保健福祉部・市民生活部が低め、消防局・企画調整部が高め）、カテゴリ差（事業・社会的意義が高く
働き方・評価・処遇が低い）、役職差（管理職が高め）、年代差（30代が低め）、自由記述（回答者の約3割、テーマ辞書に当たる文）。
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
import yaml

HERE = Path(__file__).parent
LAB = ["全くそう思わない", "あまりそう思わない", "どちらともいえない", "そう思う", "非常にそう思う"]
ORG = {  # 部局: (人数比, 効果)
    "総務部": (90, 0.05), "企画調整部": (55, 0.30), "市民生活部": (110, -0.30), "保健福祉部": (150, -0.40),
    "こども未来部": (95, -0.10), "経済部": (70, 0.15), "農林水産部": (60, 0.10), "建設部": (95, -0.05),
    "環境部": (65, 0.00), "上下水道局": (75, 0.20), "教育委員会事務局": (120, -0.20), "消防局": (85, 0.35),
    "会計課": (14, 0.10), "議会事務局": (4, 0.00),
}
CAT = {"経営戦略・理念": -0.10, "経営基盤": -0.15, "事業・社会的意義": 0.45, "働き方": -0.35, "評価・処遇": -0.40,
       "組織風土": 0.15, "キャリア形成": -0.20, "コンプライアンス遵守": 0.30, "その他": 0.20}
QSHIFT = {"Q8": -0.55, "Q21": -0.40, "Q9": -0.20, "Q33": -0.15, "Q34": -0.20, "Q29": -0.15, "Q39": 0.25, "Q42": 0.20,
          "Q56": 0.10, "Q59": 0.10, "Q61": 0.15, "Q60": -0.25, "Q62": -0.05}
COMMENTS = {
    "業務量": ["人手が足りず残業が常態化している。業務量に見合った人員配置をお願いしたい。",
             "欠員が補充されず、兼務が増えて負担が大きい。", "繁忙期の業務の偏りが大きい。業務の棚卸と分担の見直しが必要だと思う。",
             "時間外勤務が多く、仕事と生活のバランスが崩れている。"],
    "上司": ["上司との面談の機会が少なく、期待されている役割が分かりにくい。", "課長が現場の状況をよく把握してくれていて助かっている。",
           "管理職によって指示の出し方や評価の基準が大きく違う。", "1on1のような定期的な対話の場があるとよい。"],
    "キャリア": ["研修の機会が限られており、専門性を高める道筋が見えにくい。", "異動の希望や適性がもっと考慮されるとやりがいが増す。",
             "若手の育成に長期的な視点で取り組んでほしい。", "学び直しやスキル習得を支援する研修の機会を増やしてほしい。"],
    "評価": ["人事評価の基準が不明確で納得感がない。", "頑張っても評価や処遇に反映されないと感じる。",
           "評価のフィードバックがほとんどなく、何を改善すべきか分からない。", "年齢や性別に関係なく公平に評価される仕組みにしてほしい。"],
    "風土": ["部署の雰囲気は良く、相談しやすい。", "前例踏襲が強く、新しい挑戦がしにくい風土がある。",
           "失敗を恐れず挑戦できる雰囲気づくりを進めてほしい。", "職員同士のコミュニケーションは良好で働きやすい。"],
    "連携": ["部署間の縦割りが強く、情報共有がうまくいっていない。", "他部署との調整に時間がかかり、進め方に無理があると感じる。"],
    "環境": ["システムやITツールの活用が進んでおらず、業務の省力化につながっていない。", "テレワークをもっと使いやすくしてほしい。",
           "グループウェアの使い方が周知されておらず、活用しきれていない。", "パソコンや端末が古く、作業効率が悪い。"],
    "WLB": ["休暇は取りやすく、ワークライフバランスは保てている。", "育児や介護と両立できる柔軟な働き方をもっと選べるようにしてほしい。",
           "年休を取りたいが、業務量が多く取りづらい。"],
    "制度": ["押印や決裁の手続きが煩雑で、事務の効率化を進めてほしい。", "申請書類が多く、無駄な事務作業が減らない。"],
    "肯定": ["市民の役に立っていると実感でき、やりがいを感じている。", "佐賀市で働けて満足している。", "特にありません。", "良い職場だと思う。"],
}


def build(out: Path | None = None, n: int = 1098, seed: int = 20260913) -> Path:
    rng = np.random.default_rng(seed)
    qs = yaml.safe_load(open(HERE / "questions.yaml", encoding="utf-8"))
    orgs = list(ORG); w = np.array([ORG[o][0] for o in orgs], float); w /= w.sum()
    org = rng.choice(orgs, n, p=w)
    role = rng.choice(["一般職", "管理職（課長級以上）"], n, p=[0.86, 0.14])
    age = rng.choice(["10・20代", "30代", "40代", "50代", "60代以上"], n, p=[0.18, 0.27, 0.28, 0.22, 0.05])
    tenure = np.array([rng.choice({"10・20代": ["3年未満", "3年以上10年未満"], "30代": ["3年未満", "3年以上10年未満", "10年以上20年未満"],
                                   "40代": ["3年以上10年未満", "10年以上20年未満", "20年以上"], "50代": ["10年以上20年未満", "20年以上"],
                                   "60代以上": ["3年未満", "20年以上"]}[a]) for a in age])
    gender = rng.choice(["男性", "女性", "答えない"], n, p=[0.55, 0.42, 0.03])
    exp = rng.choice(["民間経験あり", "他自治体等経験あり", "民間・他自治体両方", "なし"], n, p=[0.28, 0.08, 0.04, 0.60])
    base = (rng.normal(0, 0.55, n) + np.array([ORG[o][1] for o in org]) + np.where(role == "管理職（課長級以上）", 0.30, 0)
            + np.where(age == "30代", -0.15, 0) + np.where(age == "10・20代", 0.05, 0))
    cols: dict[str, list] = {}
    for q in qs:
        h, r = q["header"], q["role"]
        if r == "id":
            cols[h] = [str(1001 + k) for k in range(n)]
        elif r in ("outcome", "driver"):
            z = base + rng.normal(0, 0.80, n) + CAT.get(q.get("category"), 0) + QSHIFT.get(q["id"], 0)
            if q["id"] in ("Q21", "Q22", "Q8"):   # 業務量系は部局差を強める
                z += np.array([ORG[o][1] for o in org]) * 0.8
            vals = [LAB[k] for k in np.digitize(z, [-1.3, -0.45, 0.45, 1.3])]
            miss = rng.random(n) < 0.012
            cols[h] = [("" if m else v) for v, m in zip(vals, miss)]
        elif r == "attribute":
            cols[h] = {"Q63": gender, "Q64": role, "Q65": age, "Q66": tenure, "Q67": exp, "Q68": org}[q["id"]].tolist()
        else:  # freetext
            texts = []
            for k in range(n):
                if rng.random() > 0.32:
                    texts.append(""); continue
                p_neg = 0.75 if base[k] < 0 else 0.45
                if rng.random() < p_neg:
                    keys = ["業務量", "上司", "キャリア", "評価", "風土", "連携", "環境", "WLB", "制度"]
                    pw = np.array([2.2, 1.2, 1.2, 1.6, 1.0, 0.8, 1.1, 1.0, 0.7])
                    if org[k] in ("保健福祉部", "市民生活部"): pw[0] *= 1.8
                    if org[k] == "教育委員会事務局": pw[6] *= 1.8
                    key = rng.choice(keys, p=pw / pw.sum())
                else:
                    key = rng.choice(["肯定", "風土", "WLB"], p=[0.6, 0.25, 0.15])
                t = rng.choice(COMMENTS[key])
                if rng.random() < 0.2:
                    t += rng.choice(COMMENTS[rng.choice(list(COMMENTS))])
                texts.append(t)
            cols[h] = texts
    out = out or (HERE / "data" / "R8_回答.csv")
    out.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(cols).to_csv(out, index=False, encoding="utf-8-sig")
    return out


if __name__ == "__main__":
    print(build())
